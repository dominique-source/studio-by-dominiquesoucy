// Central Studio project registry.
//
// Source of truth for every public page (homepage selections, the
// ecosystem Gravity Interface, and /projects/[slug]). Only the four
// URLs below are documented anywhere in this repository or the studio
// brief (purinstinct.com, ballersonly-by-dominiquesoucy.com,
// getinfive.com) — every other project has officialUrl: null and stays
// inside the Studio presentation instead of linking out, per the brief's
// explicit "do not invent official URLs" rule.
//
// Statuses with no direct repository evidence (5D Athlete, Instinct
// nonprofit) were assigned the most conservative reading of the brief's
// own "X or Y" wording — see PROJECT_REGISTRY.md for the reasoning
// behind every non-obvious call.

export type ProjectStatus =
  | "LIVE"
  | "ACTIVE"
  | "PRIVATE_PREVIEW"
  | "IN_DEVELOPMENT"
  | "CONCEPT"
  | "FUTURE";

export type ProjectCategory =
  | "sport"
  | "community"
  | "media"
  | "platform"
  | "app"
  | "education"
  | "event"
  | "brand"
  | "nonprofit"
  | "manifesto"
  | "speaking"
  | "future";

export type ProjectMaturity =
  | "proven"
  | "operating"
  | "piloting"
  | "building"
  | "exploring"
  | "dormant";

export type AccessLevel = "public" | "preview" | "private";

export interface Project {
  title: string;
  slug: string;
  category: ProjectCategory;
  status: ProjectStatus;
  accessLevel: AccessLevel;
  maturity: ProjectMaturity;
  /** Ring index in the Gravity Interface: 1 = closest to the Studio nucleus. */
  orbit: 1 | 2 | 3 | 4;
  /** 1 (minor) to 3 (flagship) — drives node size and typographic scale. */
  visualWeight: 1 | 2 | 3;
  accentColor: string;
  summary: string;
  /** Optional path to a public/assets/studio image; most entries have none. */
  image: string | null;
  officialUrl: string | null;
  relationships: string[];
  featured: boolean;
  visibility: boolean;
  ctaLabel: string;
}

