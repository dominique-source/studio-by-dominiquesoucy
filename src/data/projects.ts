export function getVisibleProjects(): Project[] {
  return PROJECTS.filter((p) => p.visibility);
}

export function getProjectBySlug(slug: string): Project | undefined {
  return PROJECTS.find((p) => p.slug === slug);
}

export function getFeaturedProjects(): Project[] {
  return PROJECTS.filter((p) => p.featured && p.visibility);
}

export function getRelatedProjects(project: Project): Project[] {
  return project.relationships
    .map((slug) => getProjectBySlug(slug))
    .filter((p): p is Project => Boolean(p && p.visibility));
}

